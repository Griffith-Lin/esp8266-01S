/* UDP 传输模块（纯传输层）

   和 tcp_client.h 是一对：接口形状几乎一样，只是底层换成了 UDP。

   为什么 UDP 这边没有"连接"这回事？
     UDP 不建立连接，也没有客户端/服务端的角色之分 ——
     不需要 connect()，不需要 listen()/accept()，一个 socket 就能收发。
     这个模块做的事只有两件：bind 住本机一个端口，然后 sendto 到主节点。

   ── 和 TCP 最本质的差别：UDP【保留消息边界】 ────────────────────

     TCP 那边你点一次"发送"，ESP 的 recv() 可能分两次收到，也可能
     和下一次粘在一起（见 main.c 里"坑 1"那段）。UDP 不会这样：
     发一次 = 收一次，一包就是一包，长度固定。

     ⚠ 但这【不能】让 main.c 里那套"先攒进缓冲区再找关键字"的逻辑退休 ——
       拆包确实不可能了，粘包却仍然可能：发送方完全可以在一包里塞
       "开灯关灯"两条命令。所以那边的循环匹配照样是必须的。
       换句话说 UDP 帮你消掉了一半的坑，另一半还在。

   ── 主节点的地址仍然是硬编码的 ──────────────────────────────────

     和 TCP 那边同一个理由：192.168.4.1 是 SoftAP 的固定地址，不是
     DHCP 分的，所以可以放心写死。详见 tcp_client.c 顶部的说明。

   ⚠ 这个模块【不】从收到的包里去"学习"主节点的地址。
     想学的话很容易（recvfrom 会给出源地址），但那样等于让热点里
     任何一台设备，只要往本机端口丢一包，就能把自己变成"主节点"。
     写死地址虽然死板，但它把"谁能指挥这个节点"钉死在编译期。

   服务端地址和端口在 udp_client.c 顶部。 */

#pragma once

/* 收到数据的回调。data 是裸字节，len 是这一包的字节数。

   ⚠ 和 tcp_client 的回调不同，这里 len 就是【发送方一次 sendto 的长度】，
     不会多也不会少。回调返回后这块内存就作废，要用请自己拷走。 */
typedef void (*udp_rx_handler_t)(const char *data, int len);

/* 注册收到数据的回调。必须在 udp_client_start() 之前调用。 */
void udp_client_set_rx_handler(udp_rx_handler_t handler);

/* 启用 UDP。

   任务只会被创建一次，重复调用等于"确保它开着" —— 从别的模式切回来时
   直接调它就行，不会多出一条任务。 */
void udp_client_start(void);

/* 停用 UDP：关掉 socket，任务转成空转，但【不退出】。

   这样设计是因为调用它的地方（main.c 切链路的那个函数）本身就跑在
   接收回调里，也就是跑在传输任务【自己】的栈上 —— 如果 stop() 去
   等任务退出，就是在等自己，直接死锁。所以它只置一个标志就返回。

   代价：真正关 socket 要等 recvfrom() 那一轮超时（最多 5 秒）。
   这段窗口里到达的包会被 main.c 的双重检查挡掉，不会被执行。 */
void udp_client_stop(void);

/* 往主节点发一个数据报。len 传 0 表示自动按字符串长度算。

   返回实际发出的字节数；返回 -1 表示当前没在用（数据被丢弃）。
   ⚠ UDP 的发送是"发出去就不管了"：这里返回成功【不代表】对方收到了。
     链路断、对方没开、对方端口没人监听，本地都看不出来。 */
int udp_client_send(const char *data, int len);
