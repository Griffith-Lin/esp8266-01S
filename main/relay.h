/**
  * @file    relay.h
  * @brief   继电器 —— 对外接口
  *
  * 这个模块只管一件事：GPIO0 上那根线拉高还是拉低。
  * 它不知道"命令"、不知道"网络"，谁来调都一样。
  *
  * @par 和"开灯"的对应关系
  *
  *   本模块的接口是按【电平】命名的（on = 高），不是按"开灯 / 关灯"。
  *   继电器接的是常闭还是常开触点，决定了到底哪个电平才亮灯 ——
  *   那是硬件的事，代码这边只保证"on 就是 GPIO0 高"。
  *
  * @warning 上电后继电器是【关】的（GPIO0 低）。这是有意的：
  *          不给电就动作是最容易被忽略、也最容易出事的一类 bug。
  *          要改成上电即吸合，先想清楚为什么。
  *
  * @see     README §9.8 —— GPIO0 做输出的两个硬件坑，以及供电不足
  *          伪装成"程序跑飞"的那一段
  */

#pragma once

/**
  * @brief 把 GPIO0 配成继电器输出，并置成"关"的状态
  *
  * @note  上电默认不动作，见文件头的 @warning。
  *
  * @warning 必须在任何 relay_on() 之前调用，而且【只调一次】。
  */
void relay_init(void);

/**
  * @brief 继电器吸合（GPIO0 拉高）
  *
  * @warning GPIO0 是 ESP8266 的启动模式选择脚（strapping pin）：复位采样时
  *          它为低，芯片会直接进 UART 下载模式，【程序根本不运行】。
  *          所以"关灯"时这根线正好处在危险电平 —— 任何要加重启的地方，
  *          都必须先把 GPIO0 拉高（也就是 relay_on()）再复位。
  *
  * @warning 复位采样那一刻 GPIO0 是【输入 / 高阻态】，把它读成高的是上拉电阻，
  *          而上拉电阻不是驱动器。真正决定命运的是【挂在这根线上的外部电路】。
  */
void relay_on(void);

/** @brief 继电器释放（GPIO0 拉低） */
void relay_off(void);
